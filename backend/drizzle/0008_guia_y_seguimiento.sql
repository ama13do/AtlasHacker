-- ─────────────── Precisión pública (metodología: Excel Atlas_Obligaciones_HxNF) ───────────────
-- Modo protección (amenazas) → el público solo ve el estado, con el pin en el centro del estado.
-- Megaproyectos (MP.*)        → el pin va al centro del municipio.
-- Los nombres llegan del geocodificador o escritos a mano: se normalizan (sin acentos, minúsculas,
-- sin «de Zaragoza», «Municipio de», etc.) antes de buscarlos.
CREATE OR REPLACE FUNCTION public.geo_norm(t text) RETURNS text
LANGUAGE sql IMMUTABLE AS $$
  SELECT nullif(btrim(regexp_replace(translate(lower(coalesce(t, '')), 'áéíóúüñàèìòùäëïö.', 'aeiouunaeiouaeio '), '\s+', ' ', 'g')), '')
$$;--> statement-breakpoint
CREATE OR REPLACE FUNCTION public.geo_norm_entidad(t text) RETURNS text
LANGUAGE sql IMMUTABLE SET search_path = public AS $$
  SELECT CASE n
    WHEN 'estado de mexico' THEN 'mexico'
    WHEN 'edomex' THEN 'mexico'
    WHEN 'edo mex' THEN 'mexico'
    WHEN 'cdmx' THEN 'ciudad de mexico'
    WHEN 'distrito federal' THEN 'ciudad de mexico'
    ELSE regexp_replace(n, ' de (zaragoza|ocampo|ignacio de la llave)$', '')
  END FROM (SELECT geo_norm(t) AS n) s
$$;--> statement-breakpoint
CREATE OR REPLACE FUNCTION public.geo_norm_municipio(t text) RETURNS text
LANGUAGE sql IMMUTABLE SET search_path = public AS $$
  SELECT regexp_replace(regexp_replace(geo_norm(t), '^municipio (de )?', ''), ' municipality$', '')
$$;--> statement-breakpoint

